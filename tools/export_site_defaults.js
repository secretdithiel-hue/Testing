// Writes site/assets/js/defaults.js: the website's built-in copy of the settings the web app
// sends (competitions, prices, answer options, the submission form's questions). The website
// uses it in preview mode and when the spreadsheet cannot be reached.
// Run after changing SYSTEM_CONFIG:  node tools/export_site_defaults.js
'use strict';
const fs = require('fs');
const path = require('path');
const { makeWebEnv } = require('../tests/web_env');

function siteDefaults(codePath) {
  const env = makeWebEnv(codePath);
  const cfg = JSON.parse(JSON.stringify(env.ctx.webConfig_()));
  delete cfg.registration; delete cfg.submission; delete cfg.serverTime;
  cfg.paymentMethods = []; cfg.dates = [];
  return cfg;
}

function render(cfg) {
  return '// Generated by tools/export_site_defaults.js from src/Code.gs. Do not edit by hand.\n' +
    'window.HNS_DEFAULTS = ' + JSON.stringify(cfg, null, 1) + ';\n';
}

if (require.main === module) {
  const root = path.join(__dirname, '..');
  const out = path.join(root, 'site/assets/js/defaults.js');
  fs.writeFileSync(out, render(siteDefaults(path.join(root, 'src/Code.gs'))));
  console.log('wrote ' + path.relative(root, out));
}
module.exports = { siteDefaults, render };
